/*
Задание №1
Выведите информацию о фильмах, у которых рейтинг “R” и стоимость аренды указана от 0.00 до 3.00 включительно,
 а также фильмы c рейтингом “PG-13” и стоимостью аренды больше или равной 4.00.
В результирующей таблице должны быть следующие столбцы: название фильма, рейтинг, стоимость аренды.
*/
select title, rating, rental_rate 
from film f 
where (rating = 'R' and rental_rate between '0' and '3')
	or (rating = 'PG-13' and rental_rate >= '4') ;

/*
 Задание №2
Получите информацию о трёх фильмах с самым длинным описанием фильма.
В результирующей таблице должны быть следующие столбцы: название фильма, описание, количество символов в описании. 
 */
select title, description, length(description)
from film f 
order by length(description) desc limit 3 ;

/*
 Задание №3
Выведите Email каждого покупателя, разделив значение Email на 2 отдельных колонки:
в первой колонке должно быть значение, указанное до @,
во второй колонке должно быть значение, указанное после @.
В результирующей таблице должны быть следующие столбцы: email, имя почтового ящика, домен.
 */
select 
	email,
	split_part(email, '@', 1),
	split_part(email, '@', 2) 
from customer c ;

/*
Задание №4
Доработайте запрос из предыдущего задания, скорректируйте значения в новых колонках: первая буква строки должна быть заглавной,
 остальные строчными. В результирующей таблице должны быть следующие столбцы: email, имя почтового ящика, домен.
*/
select 
	concat(upper(left(email, 1)), '', lower(substring(email, 2))),
	concat(upper(left(split_part(email, '@', 1), 1)), '' , lower(substring(split_part(email, '@', 1), 2))),
	concat(upper(left(split_part(email, '@', 2), 1)), '' , lower(substring(split_part(email, '@', 2), 2)))
from customer c ;
